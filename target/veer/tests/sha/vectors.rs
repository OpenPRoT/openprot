//! SHA-2 test vectors. The digests were computed with Python's hashlib.

/// Short messages and their names. The 448-bit and 896-bit messages are from
/// the FIPS 180 examples. With padding, the 896-bit message takes two SHA-384
/// or SHA-512 blocks.
pub const MESSAGES: [(&str, &[u8]); 4] = [
    ("empty", b""),
    ("abc", b"abc"),
    ("448 bits", b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
    ("896 bits", b"abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu"),
];

/// Length of the pattern message, whose byte `i` is `i % 251`. It is longer
/// than the 4096 bytes that one mailbox command can carry.
pub const PATTERN_LEN: usize = 5000;

/// The pattern message.
pub static PATTERN: [u8; PATTERN_LEN] = {
    let mut pattern = [0; PATTERN_LEN];
    let mut i = 0;
    while i < PATTERN_LEN {
        pattern[i] = (i % 251) as u8;
        i += 1;
    }
    pattern
};

/// Length of the start of the pattern message that the test writes in small
/// pieces.
pub const PIECES_LEN: usize = 1000;

/// Digests for one algorithm with `L`-byte digests.
pub struct Digests<const L: usize> {
    /// Digests of `MESSAGES`, in order.
    pub messages: [[u8; L]; 4],
    /// Digest of the pattern message.
    pub pattern: [u8; L],
    /// Digest of the first `PIECES_LEN` bytes of the pattern message.
    pub pieces: [u8; L],
}

