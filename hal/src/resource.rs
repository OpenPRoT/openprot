//! Peripheral-agnostic pin vocabulary: the [`Pin`] token marker, the [`Capability`]/[`Routes`] typed
//! datum binding, and the [`pins!`](crate::pins!) generator.

/// A tentative register write.
// TODO: any direct-MMIO bit/field mux; can't express ordered/timed write sequences, poll/read-back mux,
// non-`u32` registers, or off-chip (serial IO-expander) routing.
#[derive(Clone, Copy)]
pub struct FieldWrite {
    /// Register offset the modification targets.
    pub offset: u32,
    /// Bits to OR in.
    pub set: u32,
    /// Bits to AND out.
    pub clr: u32,
}

/// A helper to make a fieldwrite for setting a single bit.
#[must_use]
pub const fn set(offset: u32, bit: u8) -> FieldWrite {
    FieldWrite {
        offset,
        set: 1 << bit,
        clr: 0,
    }
}

/// Clear a single bit.
#[must_use]
pub const fn clear(offset: u32, bit: u8) -> FieldWrite {
    FieldWrite {
        offset,
        set: 0,
        clr: 1 << bit,
    }
}

/// Write a `mask`-wide field: `value` into the field at `shift` (crossbar select).
#[must_use]
pub const fn field(offset: u32, shift: u8, mask: u32, value: u32) -> FieldWrite {
    let reg_mask = mask << shift;
    let set = (value << shift) & reg_mask;
    FieldWrite {
        offset,
        set,
        clr: reg_mask & !set,
    }
}

impl FieldWrite {
    /// Merge another write to the **same** register into this one; const-panics on a set/clear
    /// conflict, so a contradictory config fails to compile rather than silently racing the bits.
    pub(crate) const fn coalesce(&mut self, w: FieldWrite) {
        assert!(
            self.offset == w.offset,
            "coalesce of writes to different registers"
        );
        assert!(
            self.set & w.clr == 0 && self.clr & w.set == 0,
            "config sets and clears the same bit"
        );
        self.set |= w.set;
        self.clr |= w.clr;
    }
}

/// A pin capability (GPIO, I2C-SCL, …): a type whose `Data` is the SoC-defined datum a pin carries
/// for that role. The HAL never reads `Data`; each peripheral defines the type and its own applier.
pub trait Capability {
    /// Data associated to a pin for enabling use of the corresponding capability.
    type Data: Copy;
}

/// A pin's binding for capability `C`.
pub trait Routes<C: Capability> {
    /// List of FieldWrites which must happen for routing the pin to its capability
    const ROUTE: &'static [FieldWrite];
    /// Data associated to the runtime usage of the pin capability
    const DATA: C::Data;
}

/// A compile time pin ownership token needed to access its register bits for routing, or runtime.
pub trait Pin {}

/// Proof the implementing type is authorized to mint pin `P` — i.e. the only thing each pin's
/// `take()` (generated by [`pins!`](crate::pins!)) will accept as evidence. Generated code is the
/// only intended source of impls: `pin_claims.rs.jinja` emits one zero-sized `Authority` type per
/// process with an impl per pin that process's own `pin_claims_<process>` manifest entry lists;
/// `kernel_pin_routes.rs.jinja` emits one for the union of every claimed pin, for the kernel's own
/// routing. A pin outside that list has no matching impl anywhere in the program, so minting it
/// fails to compile — not a runtime check to bypass, code that was never generated to call.
pub trait AuthorizesPin<P> {}

/// Generate a chip's pins.
#[macro_export]
macro_rules! pins {
    (
        $(
            $pin:ident { $( $cap:path : $route:expr => $data:expr ),+ $(,)? }
        ),+ $(,)?
    ) => {
        $(
            #[allow(non_camel_case_types)]
            pub struct $pin(());

            impl $pin {
                /// Mint this one pin's token — an unforgeable capability asserting it names real
                /// hardware. Generated per-process pin claims (`pin_claims_<process>` in the
                /// system manifest) call this once per pin a process actually claims; kernel-side
                /// routing calls it directly for whichever pins it routes.
                ///
                /// Requires `auth: A` proving the caller is [`AuthorizesPin`](crate::resource::AuthorizesPin)
                /// for this exact pin — generated code is the only intended source of such an `A`,
                /// scoped to exactly the pins the manifest grants it.
                ///
                /// # Safety
                /// Caller must ensure this exact pin is minted at most once within whichever
                /// protection domain calls it. Routing and driving are different acts performed
                /// by different privilege levels: the kernel may mint a pin to route it in the
                /// same image where the app that claims it separately mints it to drive it — that
                /// is two domains, not two owners of one. Two mints within the *same* domain is
                /// the hazard this guards against.
                #[must_use]
                pub const unsafe fn take<A: $crate::resource::AuthorizesPin<Self>>(_auth: &A) -> Self {
                    Self(())
                }
            }

            impl $crate::resource::Pin for $pin {}

            $(
                impl $crate::resource::Routes<$cap> for $pin {
                    const ROUTE: &'static [$crate::resource::FieldWrite] = {
                        // A route holds only `FieldWrite`s, so its ctors are in scope here
                        #[allow(unused_imports)]
                        use $crate::resource::{clear, field, set};
                        $route
                    };
                    const DATA: <$cap as $crate::resource::Capability>::Data = $data;
                }
            )+
        )+
    };
}
